export function applyBestSeason(player: Player): Player {
  const season = BEST_SEASON[player.name];
  if (!season) return player;
  const [year, ppr] = season;
  return {
    ...player,
    rating: ratingFromPpr(player.position, ppr),
    peakYear: year,
  };
}
