const CURVE: Record<Position, [number, number][]> = { QB, RB, WR, TE };

export function ratingFromPpr(position: Position, ppr: number): number {
  for (const [min, rating] of CURVE[position]) {
    if (ppr >= min) return rating;
  }
  return 80;
}

